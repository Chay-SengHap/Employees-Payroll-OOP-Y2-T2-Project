class Commission {
    String type;      // EXTRA_JOB, SIDE_VISIT, SALES
    double amount;
    
    int month;
    int year;
    public Commission(String type, double amount, int month, int year) {
      this.type = type;
      this.amount = amount;
      this.month = month;
      this.year = year;
    }

    


}
